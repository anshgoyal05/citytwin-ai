// Helper to generate a rectangular or polygonal footprint in [lng, lat]
const makeFootprint = (
  centerLng: number,
  centerLat: number,
  widthMeters: number,
  lengthMeters: number,
  rotationDeg: number = 0
): number[][] => {
  const degLatPerM = 1 / 111320;
  const degLngPerM = 1 / (111320 * Math.cos((centerLat * Math.PI) / 180));

  const hw = widthMeters / 2;
  const hl = lengthMeters / 2;
  const rad = (rotationDeg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  const localCorners = [
    [-hw, -hl],
    [hw, -hl],
    [hw, hl],
    [-hw, hl],
    [-hw, -hl],
  ];

  return localCorners.map(([x, y]) => {
    const rx = x * cos - y * sin;
    const ry = x * sin + y * cos;
    return [
      Number((centerLng + rx * degLngPerM).toFixed(6)),
      Number((centerLat + ry * degLatPerM).toFixed(6)),
    ];
  });
};

